import { copyFile, mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { PALETTE } from './tokens'

const FAVICON_FILES = [
  'favicon.svg',
  'favicon.ico',
  'favicon-16.png',
  'favicon-32.png',
  'favicon-48.png',
  'apple-touch-icon.png',
  'icon-512.png',
]

const paletteCss = () =>
  `/* generated by brand/scripts/site-sync.ts · run \`bun run brand\` */\n:root {\n${Object.entries(
    PALETTE,
  )
    .map(([name, hex]) => `  --${name}: ${hex};`)
    .join('\n')}\n}\n`

export const syncSite = async (brandDir: string, repoDir: string) => {
  const publicDir = join(repoDir, 'public')
  const kitDir = join(brandDir, 'kit')
  await mkdir(join(publicDir, 'brand'), { recursive: true })
  await mkdir(join(repoDir, 'src/generated'), { recursive: true })

  for (const file of FAVICON_FILES) {
    const source = join(kitDir, 'favicon', file)
    if (await Bun.file(source).exists()) await copyFile(source, join(publicDir, file))
  }
  await copyFile(join(kitDir, 'social/og-card.png'), join(publicDir, 'og-card.png'))
  await copyFile(join(brandDir, 'guidelines/index.html'), join(publicDir, 'brand/index.html'))
  await Bun.write(join(repoDir, 'src/generated/brand.css'), paletteCss())
  return publicDir
}
